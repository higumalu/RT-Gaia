import type { MessageEntry, MessageParams } from './index';

/** 英文單複數：`count` 那個參數等於 1 用 `one`，否則 `many`；兩者都可以有其他 `{佔位符}`。 */
const plural =
  (count: string, one: string, many: string) =>
  (p: MessageParams): string =>
    (Number(p[count]) === 1 ? one : many).replace(/\{(\w+)\}/g, (w, k: string) => (p[k] === undefined || p[k] === null ? w : String(p[k])));

/** `pl` 用：「{n} 名詞」在 n ＝ 1 時換成的單數（只換這裡有的名詞，其他字照舊）。 */
const SINGULAR: Readonly<Record<string, string>> = { associations: 'association', cases: 'case', characters: 'character', contours: 'contour', days: 'day', drafts: 'draft', edits: 'edit', events: 'event', files: 'file', frames: 'frame', handles: 'handle', images: 'image', instances: 'instance', items: 'item', objects: 'object', pairs: 'pair', patients: 'patient', phases: 'phase', points: 'point', results: 'result', sets: 'set', shots: 'shot', steps: 'step', structures: 'structure', tags: 'tag', times: 'time', versions: 'version', voxels: 'voxel' };

/**
 * 英文單複數（可以有好幾個計數）：值裡每個「{參數} 名詞」在參數 ＝ 1 時把名詞換成單數 —— 「1 images · 3 RT objects」→「1 image · 3 RT objects」。
 * 句子的動詞也要跟著變的（「1 edit is …」）用 `plural`。
 */
const pl =
  (template: string) =>
  (p: MessageParams): string =>
    template.replace(/\{(\w+)\}( (?:[A-Z]{2,} )?([a-z][a-z-]*))?/g, (whole, k: string, phrase: string | undefined, word: string | undefined) => {
      const v = p[k];
      if (v === undefined || v === null) return whole;
      if (phrase === undefined || word === undefined) return String(v);
      const one = Number(v) === 1 ? SINGULAR[word] : undefined;
      return `${String(v)}${one === undefined ? phrase : phrase.slice(0, phrase.length - word.length) + one}`;
    });

